import json
import logging
import requests
from typing import List, Generator
from fastapi import HTTPException, status
from app.config import settings
from app.providers.provider_interface import AIProviderInterface

logger = logging.getLogger("app.providers.gemini_provider")


class GeminiProvider(AIProviderInterface):
    """
    Provider implementation for Google Gemini API (using native REST API to support new AQ. key formats).
    """

    def __init__(self):
        self.api_key = settings.GOOGLE_API_KEY
        self.model = settings.GEMINI_MODEL

        if not self.api_key:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Google API Key (for Gemini) is not configured."
            )

    def _build_payload(self, messages: List[dict]) -> dict:
        contents = []
        system_instruction = None

        for msg in messages:
            role = msg.get("role")
            content = msg.get("content", "")
            
            if role == "system":
                system_instruction = {
                    "parts": [{"text": content}]
                }
            else:
                gemini_role = "model" if role == "assistant" else "user"
                contents.append({
                    "role": gemini_role,
                    "parts": [{"text": content}]
                })

        payload = {
            "contents": contents
        }
        if system_instruction:
            payload["systemInstruction"] = system_instruction
            
        return payload

    def generate_response(self, messages: List[dict]) -> str:
        try:
            payload = self._build_payload(messages)
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"
            
            res = requests.post(url, headers={"Content-Type": "application/json"}, json=payload, timeout=30)
            if res.status_code != 200:
                if res.status_code == 404:
                    try:
                        list_url = f"https://generativelanguage.googleapis.com/v1beta/models?key={self.api_key}"
                        list_res = requests.get(list_url, timeout=10)
                        models_data = list_res.json()
                        available_models = [m.get("name").replace("models/", "") for m in models_data.get("models", [])]
                        raise Exception(f"HTTP 404. Model '{self.model}' not found. Available models for this key: {available_models}")
                    except Exception as list_err:
                        raise Exception(f"HTTP 404. Model '{self.model}' not found. Failed to list models: {list_err}. Raw response: {res.text}")
                raise Exception(f"HTTP {res.status_code}: {res.text}")
                
            data = res.json()
            candidates = data.get("candidates", [])
            if not candidates:
                raise Exception("No response generated by Gemini API.")
                
            text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
            return text
        except Exception as e:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Gemini API error: {str(e)}"
            )

    def generate_stream_response(self, messages: List[dict]) -> Generator[str, None, None]:
        yielded_any = False
        try:
            payload = self._build_payload(messages)
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:streamGenerateContent?alt=sse&key={self.api_key}"
            
            res = requests.post(url, headers={"Content-Type": "application/json"}, json=payload, stream=True, timeout=30)
            if res.status_code == 200:
                for line in res.iter_lines():
                    if line:
                        decoded = line.decode("utf-8").strip()
                        if decoded.startswith("data: "):
                            decoded = decoded[6:].strip()
                        elif decoded.startswith("[") or decoded.startswith(",") or decoded.startswith("]"):
                            decoded = decoded.lstrip("[, ]").rstrip("]")
                            
                        if not decoded or decoded == "[DONE]":
                            continue
                            
                        try:
                            data = json.loads(decoded)
                            candidates = data.get("candidates", [])
                            if candidates:
                                parts = candidates[0].get("content", {}).get("parts", [])
                                if parts:
                                    text = parts[0].get("text", "")
                                    if text:
                                        yielded_any = True
                                        yield text
                        except Exception:
                            pass
            else:
                logger.warning(f"Gemini streamGenerateContent HTTP {res.status_code}: {res.text}")
        except Exception as e:
            logger.warning(f"Gemini streaming exception: {e}")

        # Robust fallback: if SSE produced no tokens, call generate_response and yield words
        if not yielded_any:
            logger.info("Gemini SSE returned no tokens, falling back to direct generateContent for streaming")
            try:
                full_text = self.generate_response(messages)
                if full_text:
                    words = full_text.split(" ")
                    for i, w in enumerate(words):
                        yield w + (" " if i < len(words) - 1 else "")
                    return
            except Exception as e:
                raise HTTPException(
                    status_code=status.HTTP_502_BAD_GATEWAY,
                    detail=f"Gemini API error: {str(e)}"
                )
