  ai_model_preference VARCHAR(50),
  notification_preferences JSONB,
  guest_policy VARCHAR(20) DEFAULT 'allowed',
  sharing_policy VARCHAR(20) DEFAULT 'allowed',
  retention_period_days INTEGER,
  auto_archive_days INTEGER,
  history_size_limit INTEGER,
  disable_sharing BOOLEAN DEFAULT false,
  disable_exports BOOLEAN DEFAULT false,
  disable_public_links BOOLEAN DEFAULT false,
