CREATE TABLE IF NOT EXISTS mentions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id INTEGER NOT NULL REFERENCES conversation_comments(id) ON DELETE CASCADE,
