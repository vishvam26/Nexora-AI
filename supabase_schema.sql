-- 1. Companies (enterprise, must be first for FK)
CREATE TABLE IF NOT EXISTS companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  plan VARCHAR(20) DEFAULT 'FREE',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS company_settings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER UNIQUE REFERENCES companies(id) ON DELETE CASCADE,
  default_llm VARCHAR(50) DEFAULT 'gemini-1.5-flash',
  theme VARCHAR(20) DEFAULT 'dark',
  logo VARCHAR(255),
  max_file_size INTEGER DEFAULT 10485760,
  allowed_extensions JSONB
);
CREATE TABLE IF NOT EXISTS company_secrets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER REFERENCES companies(id) ON DELETE CASCADE,
  provider VARCHAR(50),
  encrypted_api_key VARCHAR(512)
);

-- 2. Users (self-ref manager_id, later company_id)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  is_active BOOLEAN DEFAULT true,
  manager_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  company_id INTEGER REFERENCES companies(id) ON DELETE SET NULL,
  company_role VARCHAR(20) DEFAULT 'EMPLOYEE',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_users_email ON users(email);
CREATE INDEX IF NOT EXISTS ix_users_manager_id ON users(manager_id);

-- Seed default company
INSERT INTO companies (id, name, plan) VALUES (1, 'Default Company', 'FREE') ON CONFLICT (id) DO NOTHING;

